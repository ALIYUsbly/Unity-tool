"""The main window: wires header, sidebar, tabs, log panel and the runner.

You normally do NOT edit this file to add buttons - edit a file in tabs/.
"""
import json
import os
import shlex

from PySide6.QtWidgets import (
    QApplication,
    QMainWindow,
    QVBoxLayout,
    QHBoxLayout,
    QWidget,
    QMessageBox,
    QTabWidget
)
from Unity.config import DEVICES_DIR, LOADERS_DIR, PROFILES_DIR
from Unity.core import detect
from Unity.core.profile_api import load_profiles
from Unity.core.backups import check_outputs, read_outputs
from Unity.core.profile_capture import (build_profile, capture_tab_values,
                                  extract_device_facts, slug, unique_id)
from Unity.core.reports import report_path, write_report
from Unity.core.runner import TaskRunner
from Unity.core.safety import (confirm_risk, confirm_sparse, find_sparse_images,
                         make_sparse_converter)
from Unity.core.tools import make_command
from Unity.tabs import ALL_TABS
from Unity.ui.dialogs import Prompts
from Unity.ui.header import BrandBar
from Unity.ui.log_panel import LogPanel
from Unity.ui.sidebar import Sidebar
from Unity.ui.widgets import label
from Unity.updates.dialog import UpdateDialog
from Unity.access.client import AccessClient
from Unity.licensing.client import load_saved_key, get_hwid, current_grant

class MainWindow(QMainWindow):

  def __init__(self):
    super().__init__()
    self.setWindowTitle("UNITY-TOOL")
    self.license_tier = "standard"

    help_menu = self.menuBar().addMenu("Help")

    check_updates = help_menu.addAction("Check for updates…")
    check_updates.triggered.connect(self.check_for_updates)

    license_status = help_menu.addAction("Licence status")
    license_status.triggered.connect(self.show_license_status)
    self.resize(1280, 820)
    self.setMinimumSize(1050, 640)

    self.profiles, self.profile_errors = load_profiles(PROFILES_DIR)
    self.runner = TaskRunner(self)
    self.log_panel = LogPanel()
    self.ui = Prompts(self, self.log_panel.write)

    # kept alive while a background sparse conversion is running -
    # see core.safety.make_sparse_converter and _on_sparse_* below
    self._sparse_thread = None
    self._sparse_worker = None
    self._sparse_ctx = None   # (tab, section, action) to resume after
    self._expected_outputs = []   # files the running read commands produce
    self._report = None           # (label, path, shown_cmds) while a report run is active
    self._run_lines = []          # output lines of that run, for the report
    # output of the most recently FINISHED run, for SAVE AS PROFILE - unlike
    # _run_lines (consumed by _save_report and only filled for report=True
    # actions), this always holds something after any run and is only reset
    # when the NEXT run starts, so the button has something to read from
    # even when the action that was run isn't itself report-flagged.
    self._last_lines = []

    root = QWidget()
    root.setObjectName("root")
    self.setCentralWidget(root)
    outer = QVBoxLayout(root)
    outer.setContentsMargins(0, 0, 0, 0)
    outer.setSpacing(0)

    header = BrandBar()
    outer.addWidget(header)

    body = QHBoxLayout()
    body.setContentsMargins(12, 8, 12, 12)
    body.setSpacing(10)
    outer.addLayout(body, 1)

    self.sidebar = Sidebar(self.profiles)
    header.changed.connect(self.sidebar.set_brand)
    self.sidebar.chosen.connect(self.on_profile)
    self.sidebar.detect_clicked.connect(self.on_detect)
    body.addWidget(self.sidebar)

    center = QVBoxLayout()
    self.note = label("", "note", wrap=True)
    self.note.hide()
    center.addWidget(self.note)
    self.tabs = QTabWidget()
    self.tabs.setDocumentMode(True)
    center.addWidget(self.tabs, 1)
    body.addLayout(center, 3)

    self.tab_objs = [cls() for cls in ALL_TABS]
    grant = current_grant()
    self.access_client = AccessClient(load_saved_key(), get_hwid(), grant)
    self._active_credit_reservation = None
    self._access_load_error = None if grant else (
        "No verified licence grant available — activate Unity and restart."
    )
    if self._access_load_error:
      self.ui.log(f"ACCESS POLICY WARNING: {self._access_load_error}")
    elif self.access_client.offline:
      self.ui.log(
          "ACCESS POLICY: running on a cached offline licence grant "
          f"(tier: {self.access_client.tier}). Credit metering is paused "
          "until the connection is back."
      )
    for index, t in enumerate(self.tab_objs):
      self.tabs.addTab(
          t.build(
              self.ui, self.run_action, self.save_as_profile,
              can_run=self._operation_allowed,
          ),
          t.title,
      )
      self.tabs.setTabEnabled(
          index,
          self._access_load_error is None and self.access_client.tab_allowed(t),
      )
    self._refresh_credit_status()

    self.runner.message.connect(self.log_panel.write)
    self.runner.busy_changed.connect(self.log_panel.set_busy)
    self.runner.busy_changed.connect(self._on_busy_changed)
    self.runner.finished.connect(self._on_task_finished)
    self.runner.message.connect(self._collect_line)
    self.log_panel.stop_clicked.connect(self.runner.stop)
    body.addWidget(self.log_panel, 2)

    for err in self.profile_errors:
      self.ui.log(f"PROFILE ERROR: {err}")
    self.ui.log(f"Loaded {len(self.profiles)} device profile(s)")

  # ------------------------------------------------------- access/credits --
  def _operation_allowed(self, tab, section, action):
    if self._access_load_error is not None:
      return False
    if not self.access_client.tab_allowed(tab):
      return False
    _feature_id, enabled, _cost = self.access_client.operation_rule(
        tab, section, action
    )
    return enabled

  def _refresh_credit_status(self):
    if self._access_load_error is not None:
      self.statusBar().showMessage(
          "Feature access unavailable — activate Unity and restart"
      )
    elif self.access_client.offline:
      self.statusBar().showMessage(
          f"Licence: {self.access_client.tier} (offline)    "
          f"Credits: {self.access_client.balance}"
      )
    else:
      self.statusBar().showMessage(
          f"Licence: {self.access_client.tier}    "
          f"Credits: {self.access_client.balance}"
      )

  def _on_task_finished(self, success):
    reservation = self._active_credit_reservation
    self._active_credit_reservation = None
    if not reservation:
      return
    try:
      result = self.access_client.settle(reservation, success)
      if success:
        self.ui.log(
            f"CREDITS: operation succeeded; {result.get('charged', 0)} "
            f"credit(s) charged. Balance: {self.access_client.balance}."
        )
      else:
        self.ui.log(
            "CREDITS: operation did not succeed; reserved credits released. "
            f"Balance: {self.access_client.balance}."
        )
      self._refresh_credit_status()
    except Exception as exc:
      self.ui.log(
          "CREDIT SETTLEMENT ERROR: the server could not confirm the "
          f"operation result ({exc}). Contact support before retrying."
      )
      QMessageBox.warning(
          self, "Credit settlement pending",
          "TSM could not confirm the credit transaction with the server. "
          "Do not repeat this operation until your credit balance has been "
          "checked in the admin dashboard."
      )

  # ---------------------------------------------------------- profiles --
  def on_profile(self, p):
    """Switch to the profile's tab and let that tab fill in its settings."""
    applied = []
    for i, t in enumerate(self.tab_objs):
      if t.platform and t.platform == p.get("platform"):
        self.tabs.setCurrentIndex(i)
        applied = t.apply_profile(self.ui, p) or []
        break
    note = p.get("notes", "")
    self.note.setText(f"Note: {note}" if note else "")
    self.note.setVisible(bool(note))
    extra = f" ({', '.join(applied)})" if applied else ""
    self.ui.log(f"PROFILE: {p['brand']} {p['model']}{extra}")
  #--------------------------------license---------------------------------
  def check_for_updates(self):
    """Open the release checker."""
    UpdateDialog(self).exec()

  def show_license_status(self):
    from Unity.licensing.client import load_saved_key

    key = load_saved_key()
    masked = (
        key[:4] + "…" + key[-4:]
        if len(key) > 10
        else "Not available"
    )

    QMessageBox.information(
        self,
        "TSM Licence",
        f"Status: Activated\n"
        f"Tier: {self.license_tier}\n"
        f"Licence: {masked}"
    )
  # ------------------------------------------------------------- save ---
  def save_as_profile(self, tab):
    """SAVE AS PROFILE button: ask for a name, pull HWID/PK_HASH/etc. out
    of the last run's output if there is any, copy any loader file into
    devices/loaders/<platform>/, write the new profile, then select it -
    which also proves the save worked, since the tab now shows the COPIED
    loader path instead of wherever the file was picked from."""
    ui = self.ui
    fields = tab.profile_fields()
    if not fields:
      return
    brand = ui.ask_text("Save as profile", "Brand (e.g. Oppo, Xiaomi):")
    if not brand:
      return
    model = ui.ask_text("Save as profile", "Model (e.g. A3s):")
    if not model:
      return
    codename = ui.ask_text(
        "Save as profile", "Codename (optional, e.g. SDM450):") or ""

    facts = extract_device_facts(tab.platform, "\n".join(self._last_lines))
    model_slug = slug(f"{brand}_{model}_{codename}" if codename
                      else f"{brand}_{model}")
    loaders_dir = os.path.join(LOADERS_DIR, tab.platform)
    captured = capture_tab_values(tab.values(), fields, loaders_dir,
                                  model_slug, devices_dir=DEVICES_DIR)
    profile = build_profile(tab.platform, brand, model, codename, captured,
                            facts)
    profile["id"] = unique_id(profile["id"],
                              {p["id"] for p in self.profiles})

    path = os.path.join(PROFILES_DIR, tab.platform, profile["id"] + ".json")
    try:
      os.makedirs(os.path.dirname(path), exist_ok=True)
      with open(path, "w", encoding="utf-8") as f:
        json.dump(profile, f, indent=2)
        f.write("\n")
    except OSError as e:
      ui.dialog("Save as profile", f"Could not write the profile:\n{e}")
      return

    ui.log(f"PROFILE SAVED: {path}")
    self.profiles, self.profile_errors = load_profiles(PROFILES_DIR)
    for err in self.profile_errors:
      ui.log(f"PROFILE ERROR: {err}")
    self.sidebar.profiles = self.profiles
    self.sidebar.refresh()
    self.on_profile(profile)   # select it now, confirming the save worked

  # ------------------------------------------------------------ detect --
  def on_detect(self):
    """Scan USB for a recognised flashing/diagnostic mode and jump to the
    matching tab. Only narrows down "which tab" and "which mode" - it does
    not identify the exact model, so it never auto-picks a specific device
    profile, only a generic one if one exists for that platform."""
    found = detect.scan()
    if not found:
      self.ui.dialog(
          "Detect device", "No known flashing/diagnostic USB mode was "
          "found.\n\nMake sure the phone is connected and in the right "
          "mode for the job you want (EDL/download mode for Qualcomm, "
          "BROM/Preloader with the right button held for MediaTek, etc.), "
          "then try again.")
      return

    platform, mode_label, vid, pid = found[0]
    if len(found) > 1:
      self.ui.log(f"DETECT: {len(found)} matching devices found, using the "
                 "first one")
    self.ui.log(f"DETECT: {mode_label} ({vid}:{pid})")

    if not platform:
      self.ui.dialog("Detect device",
                     f"Found: {mode_label} ({vid}:{pid})\n\nThis mode isn't "
                     "tied to one of the flashing tabs here (e.g. Samsung "
                     "Download Mode or plain fastboot) - pick the matching "
                     "tab yourself.")
      return

    for i, t in enumerate(self.tab_objs):
      if t.platform == platform:
        self.tabs.setCurrentIndex(i)
        break

    generic = next((p for p in self.profiles
                    if p.get("platform") == platform
                    and p.get("id", "").startswith("generic_")), None)
    if generic:
      self.on_profile(generic)
    else:
      self.ui.log(f"DETECT: switched to the {platform} tab - no generic "
                 "profile to pre-fill, set options manually")

  # ------------------------------------------------------- run a button --
  def run_action(self, tab, section, action):
    """Called when any action button is pressed."""
    ui = self.ui
    if not self.access_client.tab_allowed(tab):
      ui.dialog("Feature locked", "This tab is not included in your licence.")
      return
    _fid, enabled, _cost = self.access_client.operation_rule(
        tab, section, action
    )
    if not enabled:
      ui.dialog("Feature locked", "This operation is not enabled for your licence.")
      return
    if self.runner.busy:
      ui.dialog("Busy", "A task is already running!")
      return
    if self._sparse_thread is not None:
      ui.dialog("Busy", "A sparse-image conversion is already running!")
      return
    if not tab.check_options(ui):
      return
    cmds = action.build(ui)
    if not cmds:
      return
    if not tab.check_cmds(ui, cmds):
      return

    sparse = find_sparse_images(section.script, cmds)
    if sparse:
      if section.script == "mtk.py":
        ui.log("Converting sparse image(s) to raw before continuing - this "
               "can take a while for large partitions. The device does "
               "NOT need to be connected yet; you'll be told when it's "
               "time to connect it.")
        self._sparse_ctx = (tab, section, action)
        thread, worker = make_sparse_converter(section.script, cmds)
        # Connect to bound methods of THIS QObject (not a lambda/closure -
        # see make_sparse_converter's docstring for why that matters) so
        # Qt queues both calls back onto the main/GUI thread correctly.
        worker.progress.connect(self._on_sparse_progress)
        worker.finished.connect(self._on_sparse_finished)
        self._sparse_thread = thread
        self._sparse_worker = worker
        thread.start()
        return   # UI stays responsive; _on_sparse_finished continues the job
      elif not confirm_sparse(ui, sparse):
        return
    self._continue_run(tab, section, action, cmds)

  def _on_sparse_progress(self, text):
    """Runs on the main thread (queued connection) - safe to touch the UI."""
    self.ui.log(text)

  def _on_sparse_finished(self, cmds):
    """Runs on the main thread (queued connection). Tears down the
    background thread/worker - safe to call thread.quit()/wait() here
    since we're a different thread than the one being waited on - then
    resumes the action with either the converted cmds or None."""
    thread, worker = self._sparse_thread, self._sparse_worker
    thread.quit()
    thread.wait()
    worker.deleteLater()
    thread.deleteLater()
    self._sparse_thread = None
    self._sparse_worker = None

    tab, section, action = self._sparse_ctx
    self._sparse_ctx = None

    ui = self.ui
    if cmds is None:
      ui.log("CANCELLED: sparse conversion failed, nothing was written.")
      return
    ui.log("Sparse conversion complete - connect / power on the device "
           "now if you haven't already.")
    self._continue_run(tab, section, action, cmds)

  def _continue_run(self, tab, section, action, cmds):
    """The rest of what run_action used to do in one shot: risk warning,
    then build and start the actual job queue."""
    ui = self.ui
    if action.risk != "safe" and not confirm_risk(
        ui, action.label, action.risk, cmds, tab.risk_note(cmds)):
      ui.log(f"CANCELLED: {action.label}")
      return

    if make_command(section.script, []) is None:
      ui.log(f"CRITICAL: {section.script} not found (install it / add to "
             "PATH, or place it under the vendor folder)")
      return
    opts = tab.values()
    tab.before_run(ui, section.script, opts)
    jobs = []
    for args in cmds:
      pre = tab.pre_args(section.script, args, opts)
      flags = tab.extra_flags(section.script, args, opts)
      full = pre + list(args) + flags
      shown = " ".join(shlex.quote(c.split(".")[0]) for c in [section.script] + full)
      program, argv, cwd, env = make_command(section.script, full)
      jobs.append((shown, program, argv, cwd, env))
    self._expected_outputs = read_outputs(section.script, cmds)
    self._run_lines = []
    self._last_lines = []
    self._report = ((action.label, report_path(action.label),
                     [j[0] for j in jobs]) if action.report else None)

    # Credits are reserved before execution but deducted only after the
    # runner confirms every command exited successfully.
    try:
      reservation = self.access_client.reserve(tab, section, action)
    except Exception as exc:
      self.ui.dialog("Access / credits", str(exc))
      self._report = None
      self._run_lines = []
      return
    self._active_credit_reservation = reservation.get("reservation_id")
    if not self._active_credit_reservation and not reservation.get("offline"):
      self.ui.dialog(
          "Credit server error",
          "The server did not return a credit reservation. The operation "
          "was not started."
      )
      return
    if reservation.get("offline"):
      self.ui.log(
          "CREDITS: offline — this operation is allowed by your cached "
          "licence grant; it will not be metered until back online."
      )
    self.access_client.balance = int(
        reservation.get("credits", self.access_client.balance)
    )
    self._refresh_credit_status()
    try:
      self.runner.start(jobs)
    except Exception:
      try:
        self.access_client.settle(self._active_credit_reservation, False)
      finally:
        self._active_credit_reservation = None
      raise

  def _collect_line(self, text):
    self._last_lines.append(text)
    if self._report is not None:
      self._run_lines.append(text)

  def _save_report(self):
    """Write everything the tool printed to a text file (also when the run
    failed - partial device info is still worth keeping)."""
    if self._report is None:
      return
    (label, path, shown), self._report = self._report, None
    lines, self._run_lines = self._run_lines, []
    ok = "SUCCESS: Task completed." in lines
    try:
      write_report(path, label, shown, lines, ok)
    except OSError as e:
      self.ui.log(f"REPORT NOT SAVED: {e}")
      return
    state = "complete" if ok else "INCOMPLETE - run failed or was aborted"
    self.ui.log(f"Report saved ({state}): {path}")

  def _on_busy_changed(self, busy):
    """When a queue ends, check that every file a read was supposed to
    write really exists and is not empty (a failed backup must not look
    like a good one)."""
    if busy:
      return
    self._save_report()
    if not self._expected_outputs:
      return
    paths, self._expected_outputs = self._expected_outputs, []
    problems = check_outputs(paths)
    if problems:
      self.ui.log("READ CHECK FAILED - do not rely on these files:")
      for line in problems:
        self.ui.log("  " + line)
    else:
      self.ui.log(f"Read check OK: {len(paths)} file(s) written, "
                  "none empty.")
